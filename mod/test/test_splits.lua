local T = require('test.lib')
local Splits = T.load('splits.lua')

T.case('splits: a region ends at the next one; Chaos and the Crossroads never split', function()
	local s = Splits.new('underworld', nil)
	T.eq(s:room('F_Opening01', 1), nil, 'the first region starts')
	T.eq(s:room('F_Combat03', 40), nil)
	T.eq(s:room('Chaos_01', 60), nil, 'a Chaos detour is not a region')
	T.eq(s:room('F_PostBoss01', 300), nil, 'the post-boss room is still Erebus')
	local split = s:room('G_Intro', 312.5)
	T.eq(split.name, 'Erebus')
	T.eq(split.time, 312.5)
	T.eq(split.delta, nil, 'no PB yet')
	T.eq(s:room('G_Combat01', 320), nil)
	local last = s:clear(1357.55)
	T.eq(last.name, 'Oceanus')
	T.truthy(last.new_pb, 'the first clear is a PB')
	local pb = s:pb_record()
	T.eq(pb.total, 1357.55)
	T.eq(pb.splits[1], 312.5)
	T.eq(Splits.region('Hub_PreRun'), nil)
	T.eq(Splits.region('Dream_Intro'), nil)
end)

T.case('splits: compared with the PB split by split; only a faster total replaces the PB', function()
	local pb = { total = 1300, splits = { 300, 600, 900 } }
	local s = Splits.new('surface', pb)
	s:room('N_Opening01', 0)
	local a = s:room('O_Intro01', 294.69)
	T.eq(a.name, 'Ephyra')
	T.eq(Splits.fmt_delta(a.delta), '-0:05.31')
	local b = s:room('P_Intro01', 662)
	T.eq(Splits.fmt_delta(b.delta), '+1:02.00')
	local done = s:clear(1350)
	T.eq(done.new_pb, false)
	T.eq(Splits.fmt_delta(done.total_delta), '+0:50.00')
	T.eq(s:pb_record(), nil, 'slower: the PB stays')
	local quick = Splits.new('surface', pb)
	quick:room('N_Opening01', 0)
	T.truthy(quick:clear(1200).new_pb)
	T.eq(quick:pb_record().total, 1200)
end)

T.case('splits: Dream Dive regions are numbered (their order is random)', function()
	local s = Splits.new('dream', nil)
	s:room('H_Combat01', 5)
	T.eq(s:room('N_Opening01', 200).name, 'Region 1')
	T.eq(s:room('G_Combat02', 400).name, 'Region 2')
end)
